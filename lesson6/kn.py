# Вычисление полной энергии системы в разные моменты времени
def total_energy(T_snapshot, dx):
    """Вычисление полной тепловой энергии"""
    return np.sum(T_snapshot) * dx

energies = [total_energy(T[:, n], dx) for n in range(0, Nt, 50)]

plt.figure(figsize=(8, 5))
plt.plot(np.linspace(0, t_total, len(energies)), energies, 'r-', linewidth=2)
