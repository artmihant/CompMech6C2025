""" # Схема Кранка-Николсона для решения уравнения теплопроводности # """

"""
Реализация неявной схемы Кранка-Николсона для решения одномерного уравнения теплопроводности
в стержне с граничными условиями Неймана (∂T/∂x = 0 на концах).

Уравнение теплопроводности: ∂T/∂t = α ∂²T/∂x²

Схема Кранка-Николсона (неявная, второго порядка точности):
T[i, n+1] - T[i, n] = (r/2) * [(T[i-1, n+1] - 2*T[i, n+1] + T[i+1, n+1]) + (T[i-1, n] - 2*T[i, n] + T[i+1, n])]

где r = α * dt / dx²

Схема безусловно устойчива для любых значений dt и dx.
"""

import numpy as np
import matplotlib.pyplot as plt
from matplotlib.animation import FuncAnimation
import matplotlib.animation as animation

""" ## Параметры системы ## """

# Геометрические параметры
L = 1.0          # длина стержня, м
Nx = 50          # количество пространственных узлов
dx = L / (Nx - 1)  # шаг по пространству

# Физические параметры
alpha = 0.01     # коэффициент температуропроводности, м²/с

# Временные параметры
dt = 0.05        # шаг по времени, с (можем взять больше, чем для явной схемы!)
Nt = 1000        # количество временных шагов
t_total = Nt * dt  # общее время расчета

# Проверка числа Куранта (для информации)
courant_number = alpha * dt / dx**2
print(f"Число Куранта: {courant_number:.6f}")
print(f"Схема Кранка-Николсона безусловно устойчива для любых dt и dx.")
if courant_number > 0.5:
    print(f"Для явной схемы это значение было бы неустойчивым!")


""" ## Начальные и граничные условия ## """

# Массив для температуры
T = np.zeros((Nx, Nt))

# Пространственная сетка
x = np.linspace(0, L, Nx)

# Начальное условие: острый пик посередине
T[:, 0] = np.exp(-100 * (x - L/2)**2)  # Гауссов пик в центре

# Граничные условия Неймана: ∂T/∂x = 0 на обоих концах (теплоизолированные границы)


""" ## Реализация схемы Кранка-Николсона ## """

def crank_nicolson_heat(T, alpha, dx, dt, Nt):
    """
    Реализация схемы Кранка-Николсона для уравнения теплопроводности
    с граничными условиями Неймана (∂T/∂x = 0 на концах).

    Схема представляет собой среднее арифметическое между явной и неявной схемами,
    что обеспечивает второй порядок точности по времени и безусловную устойчивость.

    Args:
        T: массив температуры (Nx, Nt)
        alpha: коэффициент температуропроводности
        dx: шаг по пространству
        dt: шаг по времени
        Nt: количество временных шагов

    Returns:
        T: обновленный массив температуры
    """

    r = alpha * dt / dx**2  # число Куранта

    # Формирование трехдиагональной матрицы (постоянна на всех шагах)
    # Система: A * T[n+1] = b[n]
    # Трехдиагональная матрица: lower * T[i-1] + diag * T[i] + upper * T[i+1] = rhs[i]
    
    lower = np.zeros(Nx)      # нижняя диагональ (коэффициент при T[i-1])
    diag = np.zeros(Nx)       # главная диагональ (коэффициент при T[i])
    upper = np.zeros(Nx)      # верхняя диагональ (коэффициент при T[i+1])
    
    # Граничное условие Неймана на левом конце (i=0)
    diag[0] = 1 + r
    upper[0] = -r
    
    # Внутренние точки (i = 1, ..., Nx-2)
    for i in range(1, Nx - 1):
        lower[i] = -r / 2
        diag[i] = 1 + r
        upper[i] = -r / 2
    
    # Граничное условие Неймана на правом конце (i=Nx-1)
    lower[-1] = -r
    diag[-1] = 1 + r
    
    # Решение системы на каждом временном шаге
    for n in range(Nt - 1):
        # Формирование правой части уравнения
        rhs = np.zeros(Nx)
        
        # Граничное условие Неймана на левом конце
        rhs[0] = (1 - r) * T[0, n] + r * T[1, n]
        
        # Внутренние точки
        for i in range(1, Nx - 1):
            rhs[i] = (r/2) * T[i-1, n] + (1 - r) * T[i, n] + (r/2) * T[i+1, n]
        
        # Граничное условие Неймана на правом конце
        rhs[-1] = r * T[-2, n] + (1 - r) * T[-1, n]
        
        # Решение трехдиагональной системы методом прогонки
        T[:, n+1] = thomas_algorithm(lower, diag, upper, rhs)

    return T


def thomas_algorithm(a, b, c, d):
    """
    Метод прогонки (алгоритм Томаса) для решения трехдиагональной системы линейных уравнений.

    Система: a[i]*x[i-1] + b[i]*x[i] + c[i]*x[i+1] = d[i]

    Args:
        a: нижняя диагональ (коэффициенты при x[i-1]), a[0] не используется
        b: главная диагональ (коэффициенты при x[i])
        c: верхняя диагональ (коэффициенты при x[i+1]), c[n-1] не используется
        d: правая часть уравнения

    Returns:
        x: решение системы
    """
    n = len(d)
    c_prime = np.zeros(n)
    d_prime = np.zeros(n)
    x = np.zeros(n)

    # Прямой ход (forward elimination)
    c_prime[0] = c[0] / b[0]
    d_prime[0] = d[0] / b[0]

    for i in range(1, n):
        denom = b[i] - a[i] * c_prime[i-1]
        if i < n - 1:
            c_prime[i] = c[i] / denom
        d_prime[i] = (d[i] - a[i] * d_prime[i-1]) / denom

    # Обратный ход (back substitution)
    x[-1] = d_prime[-1]
    for i in range(n - 2, -1, -1):
        x[i] = d_prime[i] - c_prime[i] * x[i+1]

    return x


""" ## Выполнение расчета ## """

# Запуск расчета
T = crank_nicolson_heat(T, alpha, dx, dt, Nt)

print(f"\nРасчет завершен. Общее время моделирования: {t_total:.3f} с")


