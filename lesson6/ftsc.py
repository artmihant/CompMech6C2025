""" # Явный метод Эйлера для решения уравнения теплопроводности # """

"""
Реализация явного метода Эйлера для решения одномерного уравнения теплопроводности
в стержне с фиксированными граничными условиями.

Уравнение теплопроводности: ∂T/∂t = α ∂²T/∂x²

Явная схема Эйлера: T[i, n+1] = T[i, n] + α * dt/dx² * (T[i-1, n] - 2*T[i, n] + T[i+1, n])
"""

import numpy as np
import matplotlib.pyplot as plt
from matplotlib.animation import FuncAnimation
import matplotlib.animation as animation

""" ## Параметры системы ## """

# Геометрические параметры
L = 1.0          # длина стержня, м
Nx = 50          # количество пространственных узлов
dx = L / (Nx - 1)  # шаг по пространству

# Физические параметры
alpha = 0.01     # коэффициент температуропроводности, м²/с

# Временные параметры
dt = 0.02      # шаг по времени, с
Nt = 1000        # количество временных шагов
t_total = Nt * dt  # общее время расчета

# Проверка условия устойчивости явной схемы
stability_criterion = alpha * dt / dx**2
print(f"Число Куранта: {stability_criterion:.6f}")
if stability_criterion > 0.5:
    print(f"ВНИМАНИЕ: Схема может быть неустойчивой! Рекомендуется dt <= {dx**2/(2*alpha):.6f}")
else:
    print("Схема устойчива.")


""" ## Начальные и граничные условия ## """

# Массив для температуры
T = np.zeros((Nx, Nt))

# Пространственная сетка
x = np.linspace(0, L, Nx)

# Начальное условие: острый пик посередине
T[:, 0] = np.exp(-100 * (x - L/2)**2)  # Гауссов пик в центре

# Граничные условия Неймана: ∂T/∂x = 0 на обоих концах (теплоизолированные границы)
# Начальные значения на границах будут установлены после первого временного шага


""" ## Реализация явного метода Эйлера ## """

def explicit_euler_heat(T, alpha, dx, dt, Nt):
    """
    Реализация явного метода Эйлера для уравнения теплопроводности
    с граничными условиями Неймана (∂T/∂x = 0 на концах)

    Args:
        T: массив температуры (Nx, Nt)
        alpha: коэффициент температуропроводности
        dx: шаг по пространству
        dt: шаг по времени
        Nt: количество временных шагов

    Returns:
        T: обновленный массив температуры
    """

    r = alpha * dt / dx**2  # число Куранта

    for n in range(Nt - 1):
        # Вычисление внутренних узлов
        for i in range(1, Nx - 1):
            T[i, n+1] = T[i, n] + r * (T[i-1, n] - 2*T[i, n] + T[i+1, n])

        # Применение граничных условий Неймана: ∂T/∂x = 0
        # Левый конец: T[0, n+1] = T[1, n+1] (симметрия)
        T[0, n+1] = T[1, n+1]
        # Правый конец: T[-1, n+1] = T[-2, n+1] (симметрия)
        T[-1, n+1] = T[-2, n+1]

    return T


""" ## Выполнение расчета ## """

# Запуск расчета
T = explicit_euler_heat(T, alpha, dx, dt, Nt)

print(f"Расчет завершен. Общее время моделирования: {t_total:.3f} с")


""" ## Визуализация результатов ## """

#%matplotlib inline

# Создание анимации распределения температуры
fig, ax = plt.subplots(figsize=(10, 6))
line, = ax.plot(x, T[:, 0], 'b-', linewidth=2)
ax.set_xlabel('Положение вдоль стержня, м')
ax.set_ylabel('Температура, °C')
ax.set_title(f'Распределение температуры, t = {0:.4f} с')
ax.grid(True, alpha=0.3)
ax.set_xlim(0, L)
ax.set_ylim(-0.1, 1.2)

def animate(frame):
    line.set_ydata(T[:, frame])
    current_time = frame * dt
    ax.set_title(f'Распределение температуры, t = {current_time:.4f} с')
    return line,

# Создание анимации
ani = FuncAnimation(fig, animate, frames=Nt, interval=50, blit=True, repeat=False)

# Отображение анимации на экране
# plt.show()  # Раскомментируйте эту строку для просмотра анимации на экране

# Сохранение анимации
ani.save('heat_conduction_euler.gif', writer='pillow', fps=20, dpi=80)

print("Анимация сохранена в файл 'heat_conduction_euler.gif'")
print("Для просмотра анимации на экране раскомментируйте строку plt.show() в коде")


""" ## Анализ результатов ## """

# Вычисление полной энергии системы в разные моменты времени
def total_energy(T_snapshot, dx):
    """Вычисление полной тепловой энергии"""
    return np.sum(T_snapshot) * dx

energies = [total_energy(T[:, n], dx) for n in range(0, Nt, 50)]

plt.figure(figsize=(8, 5))
plt.plot(np.linspace(0, t_total, len(energies)), energies, 'r-', linewidth=2)
plt.xlabel('Время, с')
plt.ylabel('Полная тепловая энергия')
plt.title('Эволюция полной тепловой энергии системы')
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.savefig('energy_evolution_euler.png', dpi=150, bbox_inches='tight')
plt.close()

print("График эволюции энергии сохранен в 'energy_evolution_euler.png'")


